"""Assemble the GitHub Pages site. Run: uv run python build_site.py

The four reports are build artefacts, regenerated by their own scripts and
git-ignored in `out/`. This copies them into `docs/` — which is what Pages
serves — and writes an index that describes each one and says which figures
supersede which, because three of the four contain answers that a later phase
revised.

Deliberately dumb: it copies rather than regenerates. Run the analysis
scripts first; this only publishes what they produced, so the site can never
disagree with `out/`.
"""

from __future__ import annotations

import shutil
from datetime import date
from pathlib import Path

from pvnight.report import STYLE

# One entry per report, in the order a reader should meet them. `status`
# carries the supersession, which matters: two of these four pages reach
# conclusions that a later phase corrected, and a reader arriving from a
# search engine has no other way to know that.
